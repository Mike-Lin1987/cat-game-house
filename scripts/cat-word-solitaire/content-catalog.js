'use strict';

function row(source) {
  const [label, symbol, ...items] = source.split('|');
  if (items.length !== 5) {
    throw new Error(`${label} 必須有 5 個固定提示詞`);
  }
  return Object.freeze({
    label,
    symbol,
    items: Object.freeze(
      items.map((item, index) =>
        Object.freeze({
          label: item,
          icon: index === 0 ? symbol : null,
        }),
      ),
    ),
  });
}

